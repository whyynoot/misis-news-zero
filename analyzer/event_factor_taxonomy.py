def event_factor_payload(base_factor: dict) -> dict:
    event = EVENT_FACTOR_TAXONOMY[base_factor["key"]]
    return {
        "factor_id": base_factor["key"],
        "dashboard_name": base_factor["name"],
        "event_name": event["event_name"],
        "event_definition": event["include"],
        "do_not_use_when": event["exclude"],
        "positive_signal": base_factor["positive_label"],
        "negative_signal": base_factor["negative_label"],
    }
